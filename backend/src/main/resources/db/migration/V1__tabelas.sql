CREATE TABLE funcao (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(30) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE usuario (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(120) NOT NULL UNIQUE,
 senha VARCHAR(100) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 bloqueado BOOLEAN NOT NULL DEFAULT FALSE,
 funcao_id BIGINT NOT NULL,
 criado_em DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_usuario_funcao FOREIGN KEY (funcao_id) REFERENCES funcao(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE cliente (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 cpf VARCHAR(14) NOT NULL UNIQUE,
 telefone VARCHAR(20),
 email VARCHAR(120),
 endereco VARCHAR(255)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE funcionario (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 cpf VARCHAR(14) NOT NULL UNIQUE,
 telefone VARCHAR(20),
 email VARCHAR(120),
 cargo VARCHAR(60),
 salario DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (salario >= 0),
 status VARCHAR(10) NOT NULL DEFAULT 'ATIVO' CHECK (status IN ('ATIVO','INATIVO')),
 usuario_id BIGINT UNIQUE,
 CONSTRAINT fk_funcionario_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE veiculo (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 marca VARCHAR(50) NOT NULL,
 modelo VARCHAR(60) NOT NULL,
 ano INT CHECK (ano BETWEEN 1900 AND 2100),
 cor VARCHAR(30),
 placa VARCHAR(8) NOT NULL UNIQUE,
 quilometragem INT CHECK (quilometragem >= 0),
 data_entrada DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 previsao_entrega DATETIME(6),
 data_entrega DATETIME(6),
 status VARCHAR(20) NOT NULL DEFAULT 'AGUARDANDO_ANALISE'
    CHECK (status IN ('AGUARDANDO_ANALISE','AGUARDANDO_PECAS','EM_MANUTENCAO',
                     'TESTES_FINAIS','CONCLUIDO','ENTREGUE')),
 cliente_id BIGINT NOT NULL,
 CONSTRAINT fk_veiculo_cliente FOREIGN KEY (cliente_id) REFERENCES cliente(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE peca (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 fabricante VARCHAR(80),
 quantidade INT NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
 valor_unitario DECIMAL(10,2) NOT NULL CHECK (valor_unitario >= 0),
 estoque_minimo INT NOT NULL DEFAULT 0 CHECK (estoque_minimo >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Os estados legados e atuais são reconhecidos, para não bloquear enums do Java.
CREATE TABLE ordem_servico (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 numero VARCHAR(20) NOT NULL UNIQUE,
 veiculo_id BIGINT NOT NULL,
 funcionario_id BIGINT,
 problema TEXT NOT NULL,
 diagnostico TEXT,
 valor_mao_obra DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (valor_mao_obra >= 0),
 valor_pecas DECIMAL(10,2) NOT NULL DEFAULT 0,
 valor_total DECIMAL(10,2) NOT NULL DEFAULT 0,
 status VARCHAR(40) NOT NULL DEFAULT 'AGUARDANDO_AVALIACAO'
    CHECK (status IN (
       'ABERTA','EM_ANDAMENTO','AGUARDANDO_PECAS','CONCLUIDA','CANCELADA',
       'AGUARDANDO_AVALIACAO','EM_AVALIACAO','AGUARDANDO_PRECIFICACAO',
       'AGUARDANDO_APROVACAO_GERENTE','AGUARDANDO_CLIENTE','REVISAO_ORCAMENTO',
       'ORCAMENTO_RECUSADO','AGUARDANDO_EXECUCAO','AGUARDANDO_PAGAMENTO',
       'AGUARDANDO_RETIRADA','VEICULO_RETIRADO','ENCERRADA')),
 data_abertura DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 data_conclusao DATETIME(6),
 CONSTRAINT fk_os_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculo(id),
 CONSTRAINT fk_os_funcionario FOREIGN KEY (funcionario_id) REFERENCES funcionario(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE item_os (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 os_id BIGINT NOT NULL,
 peca_id BIGINT NOT NULL,
 quantidade INT NOT NULL CHECK (quantidade > 0),
 valor_unitario DECIMAL(10,2) NOT NULL CHECK (valor_unitario >= 0),
 CONSTRAINT fk_item_os_os FOREIGN KEY (os_id) REFERENCES ordem_servico(id) ON DELETE CASCADE,
 CONSTRAINT fk_item_os_peca FOREIGN KEY (peca_id) REFERENCES peca(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE movimentacao_estoque (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 peca_id BIGINT NOT NULL,
 tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA','SAIDA')),
 quantidade INT NOT NULL CHECK (quantidade > 0),
 custo_unitario DECIMAL(10,2),
 os_id BIGINT,
 observacao VARCHAR(255),
 data DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_mov_peca FOREIGN KEY (peca_id) REFERENCES peca(id),
 CONSTRAINT fk_mov_os FOREIGN KEY (os_id) REFERENCES ordem_servico(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE solicitacao_peca (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 funcionario_id BIGINT NOT NULL,
 peca_id BIGINT NOT NULL,
 quantidade INT NOT NULL CHECK (quantidade > 0),
 justificativa VARCHAR(255),
 status VARCHAR(10) NOT NULL DEFAULT 'PENDENTE'
    CHECK (status IN ('PENDENTE','APROVADA','COMPRADA','RECUSADA')),
 data DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_sol_funcionario FOREIGN KEY (funcionario_id) REFERENCES funcionario(id),
 CONSTRAINT fk_sol_peca FOREIGN KEY (peca_id) REFERENCES peca(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE notificacao (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 usuario_id BIGINT NOT NULL,
 tipo VARCHAR(30) NOT NULL
    CHECK (tipo IN ('ESTOQUE_BAIXO','OS_ATRASADA','SOLICITACAO_PENDENTE',
                   'VEICULO_AGUARDANDO_PECA','SERVICO_CONCLUIDO')),
 mensagem VARCHAR(255) NOT NULL,
 lida BOOLEAN NOT NULL DEFAULT FALSE,
 data DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_notificacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE timeline_veiculo (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 veiculo_id BIGINT NOT NULL,
 evento VARCHAR(30) NOT NULL
    CHECK (evento IN ('CADASTRO','ENTRADA','DIAGNOSTICO','SOLICITACAO_PECA',
                     'APROVACAO_PECA','INICIO_CONSERTO','MUDANCA_STATUS',
                     'CONCLUSAO','ENTREGA')),
 descricao VARCHAR(255),
 usuario_id BIGINT,
 data DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_timeline_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculo(id) ON DELETE CASCADE,
 CONSTRAINT fk_timeline_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE auditoria (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 usuario_id BIGINT,
 acao VARCHAR(30) NOT NULL,
 entidade VARCHAR(50) NOT NULL,
 entidade_id BIGINT,
 detalhes TEXT,
 data DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_auditoria_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Não há entidade Java Despesa, mas o DashboardIndicadoresRepository consulta essa tabela.
CREATE TABLE despesa (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('BENEFICIO','OUTRAS')),
 descricao VARCHAR(120),
 valor DECIMAL(10,2) NOT NULL CHECK (valor >= 0),
 data DATE NOT NULL DEFAULT (CURRENT_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
