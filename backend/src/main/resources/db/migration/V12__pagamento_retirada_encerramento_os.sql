-- Os valores e os arquivos ficam no PostgreSQL e acompanham o projeto em outra máquina.
-- Não modificar a V10 ou a V11: esta é uma evolução incremental.
CREATE TABLE pagamento_os (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id BIGINT NOT NULL UNIQUE REFERENCES ordem_servico(id),
    valor NUMERIC(10,2) NOT NULL CHECK (valor >= 0),
    forma_pagamento VARCHAR(25) NOT NULL CHECK (forma_pagamento IN
        ('DINHEIRO','PIX','CARTAO_DEBITO','CARTAO_CREDITO','TRANSFERENCIA')),
    pago_em TIMESTAMP NOT NULL,
    registrado_por_usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    observacao VARCHAR(500),
    comprovante_nome VARCHAR(180),
    comprovante_mime VARCHAR(40),
    comprovante_dados BYTEA,
    CONSTRAINT chk_pagamento_comprovante_coerente CHECK (
        (comprovante_nome IS NULL AND comprovante_mime IS NULL AND comprovante_dados IS NULL) OR
        (comprovante_nome IS NOT NULL AND comprovante_mime IS NOT NULL AND comprovante_dados IS NOT NULL)
    )
);

CREATE TABLE retirada_os (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id BIGINT NOT NULL UNIQUE REFERENCES ordem_servico(id),
    nome_retirante VARCHAR(120) NOT NULL,
    retirado_em TIMESTAMP NOT NULL,
    registrado_por_usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    observacao VARCHAR(500)
);
