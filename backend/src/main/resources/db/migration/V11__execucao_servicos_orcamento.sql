-- Parte 4: acompanhamento de serviços aprovados, sem alterar V10 ou orçamentos históricos.
-- Itens do orçamento são imutáveis após resposta do cliente; o progresso fica separado.
CREATE TABLE execucao_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id BIGINT NOT NULL REFERENCES ordem_servico(id),
    item_orcamento_id BIGINT NOT NULL UNIQUE REFERENCES item_orcamento(id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDO')),
    iniciado_em TIMESTAMP,
    concluido_em TIMESTAMP
);
CREATE INDEX idx_execucao_servico_os ON execucao_servico (os_id);
