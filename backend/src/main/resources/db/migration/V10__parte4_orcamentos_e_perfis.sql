-- Orcamentos sao versoes imutaveis apos a resposta do cliente.
-- Nao alteram item_os ou movimentacao_estoque: apenas planejamento comercial.
CREATE TABLE IF NOT EXISTS orcamento (
  id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  os_id                      BIGINT NOT NULL REFERENCES ordem_servico(id),
  versao                     INTEGER NOT NULL CHECK (versao > 0),
  aprovado_gerente           BOOLEAN NOT NULL DEFAULT FALSE,
  decisao_cliente            VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
                             CHECK (decisao_cliente IN ('PENDENTE','APROVADO','ALTERACAO','RECUSADO')),
  contato_por_usuario_id     BIGINT REFERENCES usuario(id),
  registrado_por_usuario_id  BIGINT REFERENCES usuario(id),
  data_contato               TIMESTAMP,
  observacao_cliente         VARCHAR(500),
  criado_em                  TIMESTAMP NOT NULL DEFAULT now(),
  CONSTRAINT uk_orcamento_os_versao UNIQUE (os_id, versao)
);

CREATE TABLE IF NOT EXISTS item_orcamento (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orcamento_id   BIGINT NOT NULL REFERENCES orcamento(id),
  tipo           VARCHAR(10) NOT NULL CHECK (tipo IN ('SERVICO','PECA')),
  descricao      VARCHAR(255) NOT NULL,
  peca_id        BIGINT REFERENCES peca(id),
  quantidade     INTEGER NOT NULL CHECK (quantidade > 0),
  valor_unitario NUMERIC(10,2) CHECK (valor_unitario >= 0),
  CONSTRAINT chk_item_orcamento_peca CHECK (
      (tipo = 'PECA' AND peca_id IS NOT NULL) OR
      (tipo = 'SERVICO' AND peca_id IS NULL)
  )
);

-- As tabelas podem ter sido criadas em tentativa anterior ou manualmente.
-- Nao apagamos tabelas ou dados existentes. Verificamos as colunas essenciais
-- para evitar que o IF NOT EXISTS esconda uma estrutura incompatível.
DO $$
DECLARE
    v_faltando TEXT;
BEGIN
    SELECT string_agg(requisito.tabela || '.' || requisito.coluna, ', ')
      INTO v_faltando
      FROM (VALUES
        ('orcamento','id'), ('orcamento','os_id'), ('orcamento','versao'),
        ('orcamento','aprovado_gerente'), ('orcamento','decisao_cliente'),
        ('orcamento','contato_por_usuario_id'), ('orcamento','registrado_por_usuario_id'),
        ('orcamento','data_contato'), ('orcamento','observacao_cliente'),
        ('orcamento','criado_em'),
        ('item_orcamento','id'), ('item_orcamento','orcamento_id'),
        ('item_orcamento','tipo'), ('item_orcamento','descricao'),
        ('item_orcamento','peca_id'), ('item_orcamento','quantidade'),
        ('item_orcamento','valor_unitario')
      ) AS requisito(tabela, coluna)
     WHERE NOT EXISTS (
        SELECT 1 FROM pg_attribute atributo
         WHERE atributo.attrelid = to_regclass(requisito.tabela)
           AND atributo.attname = requisito.coluna
           AND atributo.attnum > 0
           AND NOT atributo.attisdropped
     );

    IF v_faltando IS NOT NULL THEN
        RAISE EXCEPTION 'A estrutura existente do orcamento nao e compativel. Colunas faltando: %',
            v_faltando
            USING HINT = 'Nao exclua dados. Compare as tabelas existentes com a migration V10.';
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_orcamento_os ON orcamento(os_id, versao DESC);
